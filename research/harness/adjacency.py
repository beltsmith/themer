"""Within-line role adjacency (framework C6: confusion cost = sum adjacency * w).

From data/cache/role_tokens.pkl (harness/role_tokens.py), per language and pooled:
  cooccur_line         fraction of non-blank lines containing both roles
                       (i == j: lines with >= 2 distinct tokens of role i)
  adjacent_raw         fraction of adjacent segment pairs on the same line that are
                       the unordered pair {i, j}; every visible segment counts,
                       punctuation included
  adjacent_skip_punct  the same after dropping punctuation segments (so `foo(bar`
                       makes function.call~variable.use adjacent); `default` is kept
                       because it is a role in the pair weights (comment/default)
Rows are unordered pairs with role_a <= role_b.  Each adjacency column sums to 1
over pairs within a language.  lang=ALL = unweighted mean over languages
excluding elisp (rows absent in a language count as 0).

Writes out/adjacency.csv and out/adjacency.md.
Run: uv run --with pandas --with numpy --with pyyaml python harness/adjacency.py
"""
import pickle
from collections import Counter, defaultdict
from itertools import combinations
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "out"
EXCLUDE_FROM_ALL = {"elisp"}
COLS = ["cooccur_line", "adjacent_raw", "adjacent_skip_punct"]


def pair(a, b):
    return (a, b) if a <= b else (b, a)


def adj_counts(seg):
    c = Counter()
    f, l0, l1, r = seg.file.values, seg.l0.values, seg.l1.values, seg.role.astype(str).values
    same = (f[1:] == f[:-1]) & (l0[1:] == l1[:-1])
    for a, b in zip(r[:-1][same], r[1:][same]):
        c[pair(a, b)] += 1
    return c


def lang_rows(seg, lines):
    seg = seg.sort_values(["file", "s"]).reset_index(drop=True)
    nonblank = {(fi, ln) for fi, lns in lines.items() for ln in lns}
    per_line = defaultdict(lambda: defaultdict(set))
    for fi, occ, role, a, b in zip(seg.file.values, seg.occ.values, seg.role.astype(str).values,
                                   seg.l0.values, seg.l1.values):
        for ln in range(a, b + 1):
            if (fi, ln) in nonblank:
                per_line[(fi, ln)][role].add(occ)
    co = Counter()
    for roles in per_line.values():
        rs = sorted(roles)
        for a, b in combinations(rs, 2):
            co[(a, b)] += 1
        for a in rs:
            if len(roles[a]) >= 2:
                co[(a, a)] += 1
    n_lines = len(nonblank)
    raw = adj_counts(seg)
    skip = adj_counts(seg[seg.role != "punctuation"])
    nr, ns = sum(raw.values()), sum(skip.values())
    keys = set(co) | set(raw) | set(skip)
    return {k: {"cooccur_line": co[k] / n_lines, "adjacent_raw": raw[k] / nr,
                "adjacent_skip_punct": skip[k] / ns,
                "n_cooccur": co[k], "n_raw": raw[k], "n_skip": skip[k]} for k in keys}


def main():
    with (ROOT / "data" / "cache" / "role_tokens.pkl").open("rb") as fh:
        data = pickle.load(fh)
    per = {}
    for lang, d in data.items():
        per[lang] = lang_rows(d["seg"], d["lines"])
        print(lang, len(per[lang]), "pairs", flush=True)
    langs = [l for l in per if l not in EXCLUDE_FROM_ALL]
    keys = set().union(*(per[l] for l in langs))
    rows = []
    for k in keys:
        rows.append({"lang": "ALL", "role_a": k[0], "role_b": k[1],
                     **{c: float(np.mean([per[l].get(k, {}).get(c, 0.0) for l in langs])) for c in COLS},
                     "n_langs": sum(1 for l in langs if k in per[l])})
    for l, d in per.items():
        for k, v in d.items():
            rows.append({"lang": l, "role_a": k[0], "role_b": k[1], **v})
    df = pd.DataFrame(rows).sort_values(["lang", "adjacent_skip_punct"], ascending=[True, False])
    df = pd.concat([df[df.lang == "ALL"], df[df.lang != "ALL"]])
    df.to_csv(OUT / "adjacency.csv", index=False, float_format="%.6f")
    write_md(df)
    print("wrote out/adjacency.csv, out/adjacency.md")


def write_md(df):
    w = yaml.safe_load((ROOT / "patterns" / "weights.yaml").read_text())
    a = df[df.lang == "ALL"]
    langs = [l for l in df.lang.unique() if l != "ALL"]
    L = ["# Role adjacency\n",
         "Generated by `harness/adjacency.py`; full matrix in `out/adjacency.csv` (per language and "
         "ALL = mean over languages excluding elisp). `line` = fraction of non-blank lines containing "
         "both roles; `raw` = share of same-line adjacent segment pairs; `skip` = the same with "
         "punctuation segments removed.\n",
         "## Pairs listed in patterns/weights.yaml\n",
         "| pair | w | line | raw | skip | adj x w (skip) | " + " | ".join(f"{l} skip" for l in langs) + " |",
         "|---|---:|---:|---:|---:|---:|" + "---:|" * len(langs)]
    for ra, rb, wt in w["pairs"]:
        k = pair(ra, rb)
        x = a[(a.role_a == k[0]) & (a.role_b == k[1])]
        v = x.iloc[0] if len(x) else None
        cells = []
        for l in langs:
            y = df[(df.lang == l) & (df.role_a == k[0]) & (df.role_b == k[1])]
            cells.append(f"{100 * y.adjacent_skip_punct.iloc[0]:.2f}%" if len(y) else "-")
        if v is None:
            L.append(f"| {ra} / {rb} | {wt} | - | - | - | - | " + " | ".join(cells) + " |")
        else:
            L.append(f"| {ra} / {rb} | {wt} | {100 * v.cooccur_line:.2f}% | {100 * v.adjacent_raw:.2f}% | "
                     f"{100 * v.adjacent_skip_punct:.2f}% | {wt * v.adjacent_skip_punct:.4f} | " + " | ".join(cells) + " |")
    L.append("\n## Top 25 distinct-role pairs (ALL, by skip-punctuation adjacency)\n")
    L.append("| pair | line | raw | skip |")
    L.append("|---|---:|---:|---:|")
    d = a[a.role_a != a.role_b].sort_values("adjacent_skip_punct", ascending=False).head(25)
    for v in d.itertuples():
        L.append(f"| {v.role_a} / {v.role_b} | {100 * v.cooccur_line:.1f}% | {100 * v.adjacent_raw:.2f}% | "
                 f"{100 * v.adjacent_skip_punct:.2f}% |")
    L.append("\nCaveats: adjacency is within a line only; a multi-line string/comment is adjacent to "
             "what follows it on its last line. Segments, not tokens: a string split by an escape gives "
             "string~string.escape twice. Pooled rows average languages, so a pair present in one "
             "language only is diluted by ~1/9.")
    (OUT / "adjacency.md").write_text("\n".join(L) + "\n")


if __name__ == "__main__":
    main()
