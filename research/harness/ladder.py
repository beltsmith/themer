"""H8 capacity-ladder search -> out/ladder.md

    uv run --with pyyaml python harness/ladder.py

For each pattern set, a drop order is a permutation of its hue families. At capacity c the
first N−c families of the order are dropped, and their roles follow the YAML `fallback`
(mapper_common.effective_styles). Cost at a level (C6) = Σ over the set's must-differ pairs
that are left with NO distinguishing channel (static channel model,
mapper_common.channels_between) of adjacency × w, raw and recoverability-discounted
(× (1 − lexical separability)), PLUS the beacon-loss term λ·Σ beacon·ink·loss (spec fix (b);
λ from mapper_common.beacon_lambda, sensitivity at λ/3 and 3λ). Palette-independent: kept
families are assumed to get categorically distinct accents. The YAML order is ascending
`keep` (draft 2: higher = kept longer) or ascending `ladder` (draft 1, lower = dropped first).

Since cost depends only on the kept subset, all 2^N subsets are scored once; every one of
the N! orders is then evaluated (N ≤ 8 -> ≤ 40320), and a DP over subsets gives the order
with minimum total cost (area over levels 0..N-1). H8 "holds" for a set if some single
order attains the per-level minimum (over all subsets of that size) at every level.
"""
from __future__ import annotations

import itertools
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mapper_common as M  # noqa: E402


LAM_K = 1.0   # multiplier on λ (sensitivity runs use 1/3 and 3)


def subset_costs(s, lam_k=None):
    """cost tuple per kept subset: (raw C6, disc C6, n confused, beacon loss, raw pairs only, disc pairs only).
    C6 = pair confusion + k·λ·beacon loss (spec fix (b)); λ from mapper_common.beacon_lambda()."""
    k = LAM_K if lam_k is None else lam_k
    lam = M.beacon_lambda()
    fams = M.hue_families(s)
    md = M.must_differ_pairs(s)
    v2 = M.is_v2(s)
    out = {}
    for r in range(len(fams) + 1):
        for kept in itertools.combinations(fams, r):
            st = M.effective_styles(s, set(kept))
            raw = disc = 0.0
            n = 0
            for a, b, w in md:
                if not M.channels_between(st[a], st[b], v2):
                    raw += M.pair_cost(a, b)
                    disc += M.pair_cost(a, b, True)
                    n += 1
            bl = M.beacon_loss(s, st)
            out[frozenset(kept)] = (raw + k * lam['raw'] * bl, disc + k * lam['disc'] * bl, n, bl, raw, disc)
    return fams, out


def order_vector(order, costs, idx):
    """cost at capacity c = N-1 .. 0 after dropping order[0..]."""
    kept = set(order)
    v = []
    for f in order:
        kept.discard(f)
        v.append(costs[frozenset(kept)][idx])
    return v   # v[i] = cost at capacity N-1-i


def best_chain(fams, costs, idx):
    """DP: best[S] = min total cost of dropping down from S to ∅ (sum of costs of visited proper subsets)."""
    best = {frozenset(): (0.0, [])}
    for r in range(1, len(fams) + 1):
        for S in itertools.combinations(fams, r):
            S = frozenset(S)
            cand = []
            for f in S:
                T = S - {f}
                c, path = best[T]
                cand.append((costs[T][idx] + c, [f] + path))
            best[S] = min(cand, key=lambda x: x[0])
    return best[frozenset(fams)]


def main():
    L = ['# Capacity ladder search (H8)', '',
         'Generated by `harness/ladder.py`. Drop order = which hue family is merged/dropped first as capacity falls; roles of a '
         'dropped family follow its YAML `fallback` (quiet roles: `quiet_fallback`, else default). Cost at a level = Σ adjacency × w over the '
         'set\'s must-differ pairs left with no distinguishing channel (static channel model, see static_checks.md) **+ λ · beacon loss** '
         '(Σ_roles beacon · ink · loss; loss 1 = falls to plain default, 0.5 = keeps bold or a dim/quiet/faded tier). '
         f'λ_disc = {M.beacon_lambda()["disc"]:.5f}, λ_raw = {M.beacon_lambda()["raw"]:.4f}: dropping every hue family of draft-2 landmark '
         'costs as much in beacon loss as in pair confusion. **disc.** = pair term × (1 − lexical separability), the version H8 is judged on. '
         'YAML order = ascending `keep` (draft 2) / `ladder` (draft 1). Palette-independent: kept families are assumed to get categorically distinct accents.',
         f'Adjacency: {M.adjacency()[1]}.', '']
    summary = []
    for name in M.SETS:
        s = M.load_set(name)
        fams, costs = subset_costs(s)
        N = len(fams)
        yaml_order = M.drop_order(s)
        L.append(f'## {name}\n')
        L.append(f'{N} hue families; {len(M.must_differ_pairs(s))} must-differ pairs; {N}! = {len(list(itertools.permutations(range(N))))} orders searched.\n')
        L.append(f'YAML drop order: {" → ".join(yaml_order)}.\n')
        for idx, lab in ((1, 'discounted'), (0, 'raw')):
            permin = {}
            argmin = {}
            for S, c in costs.items():
                k = len(S)
                if k not in permin or c[idx] < permin[k] - 1e-15:
                    permin[k], argmin[k] = c[idx], S
            tot_best, chain = best_chain(fams, costs, idx)
            yv = order_vector(yaml_order, costs, idx)
            bv = order_vector(chain, costs, idx)
            # does any order hit the per-level minimum everywhere?
            every = None
            for perm in itertools.permutations(fams):
                v = order_vector(perm, costs, idx)
                if all(abs(v[i] - permin[N - 1 - i]) <= 1e-12 for i in range(N)):
                    every = perm
                    break
            L.append(f'### {lab} cost\n')
            L.append(f'Optimal order (min total over levels): {" → ".join(chain)}. '
                     f'Total: optimal {tot_best:.5g}, YAML {sum(yv):.5g}, gap {sum(yv) - tot_best:.5g} '
                     f'({(sum(yv) / tot_best - 1) * 100 if tot_best > 0 else float("nan"):.0f}% over optimal).\n')
            L.append(f'Per-level optimal achievable by one order (H8): **{"yes" if every else "no"}**'
                     + (f' ({" → ".join(every)})' if every and list(every) != chain else '') + '.\n')
            L.append('| capacity | YAML kept | YAML cost | optimal-order kept | optimal-order cost | per-level min | min-cost kept set | gap (YAML − min) |')
            L.append('|---:|---|---:|---|---:|---:|---|---:|')
            full = costs[frozenset(fams)][idx]
            L.append(f'| {N} | all | {full:.4g} | all | {full:.4g} | {full:.4g} | all | 0 |')
            for i in range(N):
                c = N - 1 - i
                yk = sorted(set(yaml_order[i + 1:]))
                bk = sorted(set(chain[i + 1:]))
                L.append(f"| {c} | {', '.join(yk) or '–'} | {yv[i]:.4g} | {', '.join(bk) or '–'} | {bv[i]:.4g} | {permin[c]:.4g} "
                         f"| {', '.join(sorted(argmin[c])) or '–'} | {yv[i] - permin[c]:.4g} |")
            L.append('')
            if idx == 1:
                summary.append((name, ' → '.join(yaml_order), ' → '.join(chain), sum(yv), tot_best, bool(every)))
        # top cost contributors at YAML levels (discounted)
        L.append('Largest discounted contributors at each YAML level (pairs that lose their last channel):\n')
        kept = set(fams)
        st0 = M.effective_styles(s, kept)
        prev = {(a, b) for a, b, w in M.must_differ_pairs(s) if not M.channels_between(st0[a], st0[b])}
        for f in yaml_order:
            kept.discard(f)
            st = M.effective_styles(s, kept)
            lost = []
            for a, b, w in M.must_differ_pairs(s):
                if not M.channels_between(st[a], st[b]):
                    lost.append((M.pair_cost(a, b, True), M.pair_cost(a, b), a, b))
            new = [x for x in lost if (x[2], x[3]) not in prev]
            prev |= {(x[2], x[3]) for x in lost}
            new.sort(reverse=True)
            L.append(f"- drop **{f}** (capacity {len(kept)}): {len(new)} newly confused pairs; top: "
                     + ', '.join(f'{a}/{b} {d:.2g} (raw {r:.2g})' for d, r, a, b in new[:4]))
        L.append('')
    # λ sensitivity: optimal order (discounted) at k·λ
    global LAM_K
    sens = ['## Sensitivity of the optimal order to λ (discounted cost)\n',
            '| set | YAML order | pairs only (k = 0) | k = 1/3 | k = 1 | k = 3 |', '|---|---|---|---|---|---|']
    for name in M.SETS:
        s = M.load_set(name)
        cells = []
        for k in (0.0, 1 / 3, 1.0, 3.0):
            fams, costs = subset_costs(s, k)
            tot, chain = best_chain(fams, costs, 1)
            yv = sum(order_vector(M.drop_order(s), costs, 1))
            same = list(chain) == M.drop_order(s)
            cells.append(f"{' → '.join(chain)}{' (= YAML)' if same else f' (YAML +{(yv / tot - 1) * 100 if tot else 0:.0f}%)'}")
        sens.append(f"| {name} | {' → '.join(M.drop_order(s))} | " + ' | '.join(cells) + ' |')
    sens.append('')
    L.insert(5, '## Summary (discounted cost, k = 1)\n')
    L.insert(6, '| set | YAML order | optimal order | YAML total | optimal total | gap | one order optimal at every level? |')
    L.insert(7, '|---|---|---|---:|---:|---:|---|')
    for i, (n, y, b, ys, bs, ev) in enumerate(summary):
        L.insert(8 + i, f'| {n} | {y} | {b} | {ys:.4g} | {bs:.4g} | {ys - bs:.4g} ({(ys / bs - 1) * 100 if bs else float("nan"):.0f}%) | {"yes" if ev else "no"} |')
    L.insert(8 + len(summary), '')
    for i, x in enumerate(sens):
        L.insert(9 + len(summary) + i, x)
    L.append('## Caveats\n')
    L.append('- `oddball` (comment.todo) has zero measured ink and adjacency (no injections in the corpus), so confusion cost never '
             'penalises dropping it; its value is beacon value, which C6 does not count. Optimal orders that drop oddball first reflect this.')
    L.append('- Static channel model: lightness counts only for designed differences (faded, lightness variant, popout); default vs '
             'salient Lc targets are not counted. With a real palette some "hue-only" pairs also differ in lightness.')
    L.append('- Ties in `ladder` ranks (hybrid_v1) are broken by YAML order.')
    L.append('- Families whose fallback keeps a non-hue channel (definition → bold, prose → faded + italic) cost ~0 in pair confusion to drop; '
             'the beacon-loss term now charges 0.5 · beacon · ink for them. Whether that is enough to keep them depends on λ (sensitivity table).')
    with open(os.path.join(M.OUT, 'ladder.md'), 'w') as f:
        f.write('\n'.join(L) + '\n')
    print('wrote out/ladder.md')


if __name__ == '__main__':
    main()
